#!/usr/bin/env python3
"""Generate the FMOD proxy's export thunks and module definition.

  gen.py exports.txt <outdir>

Every FMOD 3 export becomes a thunk that counts the call and jumps to the
same function in the real library (fmodreal.dll). The functions in WRAPPED are
written by hand in audio.c instead.
"""
import os
import sys

WRAPPED = {"_FSOUND_SetSFXMasterVolume@4", "_FMUSIC_SetMasterVolume@8", "_FMUSIC_PlaySong@4"}

names = [n.strip() for n in open(sys.argv[1]) if n.strip()]
out = sys.argv[2]
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "thunks.c"), "w") as c:
    c.write("/* Generated by gen.py. */\n#include \"proxy.h\"\n\n")
    c.write("const char *const g_names[%d] = {\n" % len(names))
    c.write("".join('    "%s",\n' % n for n in names))
    c.write("};\n\n")
    for i, n in enumerate(names):
        if n in WRAPPED:
            continue
        c.write('__attribute__((naked)) void thunk_%d(void) {\n'
                '    __asm__("lock incl _g_counts+%d\\n\\tjmp *_g_real+%d");\n}\n' % (i, 4 * i, 4 * i))
    c.write("\nint index_of_wrapped(const char *name) {\n")
    for i, n in enumerate(names):
        if n in WRAPPED:
            c.write('    if (same(name, "%s")) return %d;\n' % (n, i))
    c.write("    return -1;\n}\n")
with open(os.path.join(out, "fmod.def"), "w") as d:
    d.write("LIBRARY fmod\nEXPORTS\n")
    for i, n in enumerate(names):
        target = "wrap_" + n.split("@")[0].lstrip("_") if n in WRAPPED else "thunk_%d" % i
        d.write("    %s=%s\n" % (n, target))
with open(os.path.join(out, "count.h"), "w") as h:
    h.write("#define EXPORT_COUNT %d\n" % len(names))
